console.log("operadores aritméticos");
let a = 10;
let b = 5;

console.log("Suma: " + (a + b));
console.log("Resta: " + (a - b));
console.log("Multiplicación: " + (a * b));
console.log("División: " + (a / b));
console.log("Módulo: " + (a % b));

console.log("operadores de asignación");
let c = 20;
c += 5; // c = c + 5
console.log("Asignación suma: " + c);
c -= 3; // c = c - 3
console.log("Asignación resta: " + c);
c *= 2; // c = c * 2
console.log("Asignación multiplicación: " + c);
c /= 4; // c = c / 4
console.log("Asignación división: " + c);
c %= 3; // c = c % 3
console.log("Asignación módulo: " + c);

console.log("operadores de comparación");
let d = 15;
let e = 10;

console.log("Igualdad: " + (d == e));
console.log("Desigualdad: " + (d != e));
console.log("Mayor que: " + (d > e));
console.log("Menor que: " + (d < e));
console.log("Mayor o igual que: " + (d >= e));
console.log("Menor o igual que: " + (d <= e));

console.log("operadores lógicos");
let f = true;
let g = false;

console.log("AND lógico: " + (f && g));
console.log("OR lógico: " + (f || g));
console.log("NOT lógico: " + (!f));

console.log("operadores de incremento y decremento");
let h = 5;

console.log("Incremento: " + (++h)); // Pre-incremento
console.log("Decremento: " + (--h)); // Pre-decremento
console.log("Incremento: " + (h++)); // Post-incremento
console.log("Decremento: " + (h--)); // Post-decremento

console.log("Valor final de h: " + h);
console.log("operadores de concatenación");
let str1 = "Hola";
